import { chromium } from '@playwright/test';
const URL = 'https://teleryan25.github.io/thanksgiving-2026/';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, timezoneId: 'America/Chicago' });
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', (e) => errs.push(e.message));
page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await page.goto(URL);
await page.getByTestId('now-card').waitFor({ timeout: 30000 });
console.log('projected:', (await page.getByTestId('projected').innerText()).replace(/\s+/g, ' '));
await page.evaluate(async () => { await navigator.serviceWorker.ready; });
await page.reload();
await page.waitForFunction(() => !!navigator.serviceWorker.controller, null, { timeout: 30000 });
await page.getByTestId('btn-settings').click();
await page.getByTestId('offline-status').filter({ hasText: 'Offline-ready' }).waitFor({ timeout: 30000 });
console.log('offline status:', await page.getByTestId('offline-status').innerText());
await page.getByTestId('btn-diag').click();
await page.getByTestId('diag-report').waitFor({ timeout: 60000 });
console.log('diagnostics:', (await page.getByTestId('diag-report').locator('b').first().innerText()));
await ctx.setOffline(true);
await page.reload();
await page.getByTestId('now-card').waitFor({ timeout: 30000 });
console.log('offline reload: OK');
console.log('errors:', JSON.stringify(errs));
await b.close();
